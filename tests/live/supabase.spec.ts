import {expect,test} from '@playwright/test';
import {manualCase,verifyFact} from '../helpers/case-ui';
import {createClient} from '@supabase/supabase-js';
import {randomUUID} from 'node:crypto';
import {login} from '../helpers/live-login';
test('real local Supabase Auth, case RPC decisions, Storage and reload',async({page})=>{
 test.setTimeout(120000);
 await login(page);
 const quote='Платная бронь квартиры 912 000 тенге. Local '+Date.now();
 await manualCase(page,'SQ-003',quote,'R2',true);
 await verifyFact(page,'R2',true,quote);await expect(page.locator('.risk-score strong')).toHaveText('25');
 await page.getByRole('button',{name:'Предпросмотр сигнала',exact:true}).click();
 await page.getByLabel('Обоснование решения',{exact:true}).fill('Проверка настоящего case RPC');
 await page.getByRole('button',{name:'Подтвердить сигнал',exact:true}).click();
 await expect(page.locator('.case-signal-sheet')).toContainText('Версия 1');
 await page.reload({waitUntil:'domcontentloaded'});await page.getByRole('button',{name:'Предпросмотр сигнала',exact:true}).click();
 await expect(page.locator('.case-signal-sheet')).toContainText('Проверка настоящего case RPC');
 const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'Скачать PDF',exact:true}).click();
 const file=await downloaded;await file.saveAs(test.info().outputPath('connected-server.pdf'));
 const options={auth:{persistSession:false,autoRefreshToken:false}};
 const client=createClient(process.env.SAQ_LIVE_SUPABASE_URL!,process.env.SAQ_LIVE_SUPABASE_KEY!,options);
 expect((await client.auth.signInWithPassword({email:process.env.SAQ_LIVE_EMAIL!,password:process.env.SAQ_LIVE_PASSWORD!})).error).toBeNull();
 const result=await client.from('workspaces').select('data').single();expect(result.error).toBeNull();
 const state=result.data!.data;
 const snapshot=state.caseSnapshots.at(-1),fact=state.assertions.find((a:any)=>a.caseId===snapshot.caseId);
 expect(snapshot.score).toBe(25);expect(fact.status).toBe('verified');expect(fact.actor).toBe(process.env.SAQ_LIVE_EMAIL);
 expect(snapshot.mediaManifest).toHaveLength(1);
 const media=state.media.find((m:any)=>m.id===snapshot.mediaManifest[0].id);
 expect((await client.storage.from('evidence').download(media.path)).error).toBeNull();
 const admin=createClient(process.env.SAQ_LIVE_SUPABASE_URL!,process.env.SAQ_LIVE_SERVICE_KEY!,options);
 const email=`foreign-case-${randomUUID()}@example.test`,password=randomUUID()+'Aa9!';
 const created=await admin.auth.admin.createUser({email,password,email_confirm:true});expect(created.error).toBeNull();
 try {
  const foreign=createClient(process.env.SAQ_LIVE_SUPABASE_URL!,process.env.SAQ_LIVE_SUPABASE_KEY!,options);
  const signed=await foreign.auth.signInWithPassword({email,password});expect(signed.error).toBeNull();
  expect((await foreign.rpc('initialize_workspace')).error).toBeNull();
  const headers={authorization:`Bearer ${signed.data.session!.access_token}`};
  for(const path of [`/api/cases/${snapshot.caseId}`,`/api/cases/${snapshot.caseId}/snapshots/${snapshot.id}/pdf`]) expect((await fetch('http://127.0.0.1:8005'+path,{headers})).status).toBe(404);
  expect((await foreign.storage.from('evidence').download(media.path)).error).not.toBeNull();
  await foreign.auth.signOut();
 } finally {expect((await admin.auth.admin.deleteUser(created.data.user!.id)).error).toBeNull();}
 await test.info().attach('connected-records',{body:JSON.stringify({caseId:snapshot.caseId,claimId:fact.claimId,assertionId:fact.id,actor:fact.actor,at:fact.at,snapshotId:snapshot.id,score:snapshot.score,mediaId:media.id}),contentType:'application/json'});
 await client.auth.signOut();
});

import { expect, test } from '@playwright/test';
test('real local Supabase Auth, RPC decisions, Storage upload and reload', async ({page}) => {
  expect(process.env.SAQ_LIVE_EMAIL).toBeTruthy();
  const errors: string[] = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Демо-аналитик',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill(process.env.SAQ_LIVE_EMAIL!);
  await page.getByLabel('Пароль',{exact:true}).fill(process.env.SAQ_LIVE_PASSWORD!);
  await page.getByRole('button',{name:'Войти',exact:true}).last().click();
  await expect(page.getByRole('heading',{name:'Видеть риски. Действовать вовремя.'})).toBeVisible();
  await expect(page.getByRole('button',{name:process.env.SAQ_LIVE_EMAIL!,exact:true})).toBeVisible();
  await expect(page.getByText('SUPABASE · персональное рабочее пространство',{exact:false})).toBeVisible();
  await page.goto('/#/detail/SQ-002');
  await page.getByLabel('Фото / видео / PDF').setInputFiles({name:'real-storage.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==','base64')});
  await page.getByLabel('Подпись файла').fill('Реальное локальное Storage');
  await page.getByRole('button',{name:'Сохранить файл',exact:true}).click();
  await expect(page.getByAltText('Реальное локальное Storage')).toBeVisible();
  await page.reload();
  await expect(page.getByAltText('Реальное локальное Storage')).toBeVisible();
  await page.goto('/#/signal/SQ-002');
  await page.getByLabel('Обоснование решения').fill('Проверка реального PostgreSQL RPC');
  await page.getByRole('button',{name:'Подтвердить сигнал'}).click();
  await expect(page.locator('.signal-sheet')).toContainText('Подтверждён');
  await page.reload();
  await expect(page.locator('.signal-sheet')).toContainText('Проверка реального PostgreSQL RPC');
  expect(errors).toEqual([]);
});
test('real external LLM analysis and confirmed evidence persist', async ({page}) => {
  expect(process.env.SAQ_LIVE_AI).toBe('1');
  await page.goto('/');
  await page.getByRole('button',{name:'Демо-аналитик',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill(process.env.SAQ_LIVE_EMAIL!);
  await page.getByLabel('Пароль',{exact:true}).fill(process.env.SAQ_LIVE_PASSWORD!);
  await page.getByRole('button',{name:'Войти',exact:true}).last().click();
  await expect(page.getByRole('heading',{name:'Видеть риски. Действовать вовремя.'})).toBeVisible();
  await expect(page.getByRole('button',{name:process.env.SAQ_LIVE_EMAIL!,exact:true})).toBeVisible();
  await expect(page.getByText('SUPABASE · персональное рабочее пространство',{exact:false})).toBeVisible();
  await page.goto('/#/analyze/SQ-001');
  const text='Продаём квартиры в строящемся ЖК Новый Берег. Дом ещё не введён в эксплуатацию, сдача в 2028 году. Депозит 654 000 тенге обязателен для бронирования квартиры.';
  await page.getByLabel('Текст объявления').fill(text);
  await page.getByRole('button',{name:'Проанализировать',exact:true}).click();
  await expect(page.getByText(process.env.SAQ_LIVE_MODEL!,{exact:true})).toBeVisible({timeout:45000});
  await expect(page.getByRole('button',{name:'Подтвердить R3'})).toBeVisible();
  await page.locator('.hypothesis').filter({hasText:'R2 · гипотеза'}).getByLabel('Обоснование аналитика').fill('Платёжное предложение проверено аналитиком');
  await page.getByRole('button',{name:'Подтвердить R2'}).click();
  await expect(page.getByText('Публикация и решение сохранены.')).toBeVisible();
  const h3=page.locator('.hypothesis').filter({hasText:'R3 · гипотеза'});
  await h3.getByLabel('Обоснование аналитика').fill('Нет независимого материала о вводе');
  await h3.getByRole('button',{name:'Отклонить гипотезу'}).click();
  await expect(page.locator('.ai-review-history')).toContainText('Нет независимого материала о вводе');
  await page.reload();
  await expect(page.locator('.ai-review-history')).toContainText('Платёжное предложение проверено аналитиком');
  await expect(page.locator('.ai-review-history')).toContainText('Нет независимого материала о вводе');
  await page.goto('/#/ads');
  await expect(page.getByText(text,{exact:true})).toBeVisible();
});

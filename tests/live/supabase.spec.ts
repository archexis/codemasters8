import { expect, test } from '@playwright/test';
test('real local Supabase Auth, RPC decisions, Storage upload and reload', async ({page}) => {
  test.skip(!process.env.SAQ_LIVE_EMAIL,'Run npm run test:local to create isolated test accounts');
  const errors: string[] = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Войти в систему'}).click();
  await page.getByLabel('Email',{exact:true}).fill(process.env.SAQ_LIVE_EMAIL!);
  await page.getByLabel('Пароль',{exact:true}).fill(process.env.SAQ_LIVE_PASSWORD!);
  await page.getByRole('button',{name:'Войти',exact:true}).last().click();
  await expect(page.getByRole('heading',{name:'Видеть риски. Действовать вовремя.'})).toBeVisible();
  await page.goto('/#/detail/SQ-002');
  await page.getByLabel('Фото / видео / PDF').setInputFiles({name:'real-storage.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==','base64')});
  await page.getByLabel('Подпись файла').fill('Реальное локальное Storage');
  await page.getByRole('button',{name:'Сохранить файл',exact:true}).click();
  await expect(page.getByAltText('Реальное локальное Storage')).toBeVisible();
  await page.reload();
  await expect(page.getByAltText('Реальное локальное Storage')).toBeVisible();
  await page.goto('/#/signal/SQ-002');
  await page.getByLabel('Обоснование решения').fill('Проверка реального PostgreSQL RPC');
  await page.getByRole('button',{name:'Подтвердить сигнал'}).click();
  await expect(page.locator('.signal-sheet')).toContainText('Подтверждён');
  await page.reload();
  await expect(page.locator('.signal-sheet')).toContainText('Проверка реального PostgreSQL RPC');
  expect(errors).toEqual([]);
});
